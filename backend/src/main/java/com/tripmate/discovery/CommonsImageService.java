package com.tripmate.discovery;

import com.fasterxml.jackson.databind.JsonNode;
import com.tripmate.discovery.provider.ProviderHttpClientFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestClient;
import org.springframework.web.util.HtmlUtils;
import org.springframework.web.util.UriComponentsBuilder;

import java.net.URI;
import java.net.URLDecoder;
import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.util.*;
import java.time.temporal.ChronoUnit;

/** Resolves the file's own author and licence instead of crediting an encyclopedia page. */
@Service
public class CommonsImageService {
    private final RestClient client;
    private final ExpiringCache<String, DiscoveryImage> cache = new ExpiringCache<>(1000);

    @Autowired
    public CommonsImageService(ProviderHttpClientFactory factory) { this(factory.create(5000)); }
    CommonsImageService(RestClient client) { this.client = client; }

    public DiscoveryImage resolve(String file) {
        if (file == null || !file.regionMatches(true, 0, "File:", 0, 5)) return null;
        DiscoveryImage cached = cache.get(file);
        if (cached != null) return cached;
        try {
            URI uri = UriComponentsBuilder.fromUriString("https://commons.wikimedia.org/w/api.php")
                    .queryParam("action", "query").queryParam("format", "json")
                    .queryParam("titles", file).queryParam("prop", "imageinfo")
                    .queryParam("iiprop", "url|extmetadata|mime").queryParam("iiurlwidth", 960)
                    .build().encode().toUri();
            DiscoveryImage image = fromResponse(client.get().uri(uri).retrieve().body(JsonNode.class));
            if (image != null) cache.put(file, image, Instant.now().plus(7, ChronoUnit.DAYS));
            return image;
        } catch (RuntimeException ex) {
            return null; // Missing evidence uses the neutral placeholder.
        }
    }

    public DiscoveryImage resolveUrl(String url) {
        if (url == null) return null;
        try {
            URI uri = URI.create(url);
            if (!"upload.wikimedia.org".equalsIgnoreCase(uri.getHost())) return null;
            String path = uri.getRawPath();
            if (!path.startsWith("/wikipedia/commons/")) return null;
            String[] parts = path.split("/");
            String name = path.contains("/thumb/") ? parts[parts.length - 2] : parts[parts.length - 1];
            return resolve("File:" + URLDecoder.decode(name.replace("+", "%2B"), StandardCharsets.UTF_8));
        } catch (IllegalArgumentException ex) { return null; }
    }

    /** Structured Commons depicts statements link every candidate to the exact entity. */
    public List<DiscoveryImage> depicting(String entityId) {
        if(entityId==null || !entityId.matches("Q[1-9][0-9]{0,14}"))return List.of();
        {
            URI uri=UriComponentsBuilder.fromUriString("https://commons.wikimedia.org/w/api.php")
                .queryParam("action","query").queryParam("format","json").queryParam("generator","search")
                .queryParam("gsrsearch","haswbstatement:P180="+entityId+" filetype:bitmap")
                .queryParam("gsrnamespace",6).queryParam("gsrlimit",6)
                .queryParam("prop","imageinfo").queryParam("iiprop","url|extmetadata|mime").queryParam("iiurlwidth",960)
                .build().encode().toUri();
            JsonNode response=client.get().uri(uri).retrieve().body(JsonNode.class);
            if(response!=null && response.has("error"))throw new IllegalStateException("Commons lookup unavailable");
            List<DiscoveryImage> images=new ArrayList<>();
            if(response!=null)for(JsonNode page:response.path("query").path("pages")) {
                PlacePhotoService.add(images,fromPage(page));if(images.size()>=2)break;
            }
            return List.copyOf(images);
        }
    }

    DiscoveryImage fromResponse(JsonNode response) {
        if(response!=null)for(JsonNode page:response.path("query").path("pages")) {
            DiscoveryImage image=fromPage(page);if(image!=null)return image;
        }
        return null;
    }
    private DiscoveryImage fromPage(JsonNode page) {
        JsonNode info=page.path("imageinfo").path(0), metadata=info.path("extmetadata");
        String mime=info.path("mime").asText("");
        if(!Set.of("image/jpeg","image/png","image/webp").contains(mime))return null;
        String evidence=(metadata.path("Categories").path("value").asText("")+" "+metadata.path("ImageDescription").path("value").asText("")).toLowerCase(Locale.ROOT);
        if(evidence.matches("(?s).*(ai[- ]generated|artificial intelligence|generated by|midjourney|stable diffusion|dall.e|illustration|diagram|logo|locator map|computer.generated|3d render).*$"))return null;
        String author=plain(metadata.path("Artist").path("value").asText(""));
        String license=plain(metadata.path("LicenseShortName").path("value").asText(""));
        String url=info.path("thumburl").asText(info.path("url").asText(""));
        String source=info.path("descriptionurl").asText("");
        if(author.isBlank() || !license.matches("(?i)(CC BY(?:-SA)? [0-9.]+|CC0(?: [0-9.]+)?|Public domain|PD)") || !trusted(url,"upload.wikimedia.org") || !trusted(source,"commons.wikimedia.org"))return null;
        String credit=plain(metadata.path("Credit").path("value").asText(""));
        String attribution=author+(credit.isBlank() || credit.equals(author)?"":" · "+credit);
        return new DiscoveryImage(url,source,"Wikimedia Commons",author,license,attribution,true,true);
    }
    private boolean trusted(String value,String host) {
        try {URI uri=URI.create(value);return "https".equals(uri.getScheme()) && host.equalsIgnoreCase(uri.getHost()) && uri.getUserInfo()==null && uri.getPort()==-1;}
        catch(IllegalArgumentException ex){return false;}
    }

    private String plain(String html) {
        return HtmlUtils.htmlUnescape(html.replaceAll("<[^>]*>", " ")).replaceAll("\\s+", " ").trim();
    }
}
